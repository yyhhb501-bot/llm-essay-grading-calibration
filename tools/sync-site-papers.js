'use strict';
// Sync papers-full content and answer-points into the site's vendor directory and
// generate a slim lazy-load index (site/js/vendor/papers-index.js).
// Re-run after each crawl/extraction round: node tools/sync-site-papers.js
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const VENDOR = path.join(ROOT, 'site/js/vendor');
const PAPERS_OUT = path.join(VENDOR, 'papers');
const POINTS_OUT = path.join(VENDOR, 'answer-points');

function main() {
  fs.mkdirSync(PAPERS_OUT, { recursive: true });
  fs.mkdirSync(POINTS_OUT, { recursive: true });
  const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/paper-catalog.json'), 'utf8'));
  const metaById = new Map(catalog.papers.map(p => [p.id, p]));

  // 1) papers-full docs
  const fullDir = path.join(ROOT, 'data/papers-full');
  let papersSynced = 0;
  const index = {};
  for (const f of fs.readdirSync(fullDir).filter(f => f.endsWith('.json') && f !== 'index.json')) {
    const doc = JSON.parse(fs.readFileSync(path.join(fullDir, f), 'utf8'));
    if (!doc.questions || !doc.questions.length) continue;
    fs.writeFileSync(path.join(PAPERS_OUT, doc.id + '.json'), JSON.stringify(doc));
    const qs = doc.questions.map(q => ({
      no: q.no, stem: q.stem || '', score: q.score || null,
      type: guessType(q.stem || ''), mr: materialRange(q.stem || '')
    }));
    index[doc.id] = { t: doc.title, y: doc.year, r: doc.region, m: doc.counts ? doc.counts.materials : 0, qs };
    papersSynced++;
  }

  // 2) answer-points docs (only for papers we know)
  let pointsSynced = 0;
  const pointsDir = path.join(ROOT, 'data/answer-points');
  const withPoints = new Set();
  if (fs.existsSync(pointsDir)) {
    for (const f of fs.readdirSync(pointsDir).filter(f => f.endsWith('.json') && f !== 'index.json')) {
      const doc = JSON.parse(fs.readFileSync(path.join(pointsDir, f), 'utf8'));
      if (!doc.questions || !doc.questions.length) continue;
      fs.writeFileSync(path.join(POINTS_OUT, doc.paperId + '.json'), JSON.stringify(doc));
      withPoints.add(doc.paperId);
      if (index[doc.paperId]) index[doc.paperId].ap = doc.questions.length;
      pointsSynced++;
    }
  }

  // 2b) consensus-points docs
  let consSynced = 0;
  const consOut = path.join(VENDOR, 'consensus-points');
  fs.mkdirSync(consOut, { recursive: true });
  const consDir = path.join(ROOT, 'data/consensus-points');
  if (fs.existsSync(consDir)) {
    for (const f of fs.readdirSync(consDir).filter(f => f.endsWith('.json') && f !== 'index.json')) {
      const doc = JSON.parse(fs.readFileSync(path.join(consDir, f), 'utf8'));
      if (!doc.questions || !doc.questions.length) continue;
      fs.writeFileSync(path.join(consOut, doc.paperId + '.json'), JSON.stringify(doc));
      if (index[doc.paperId]) index[doc.paperId].cons = doc.questions.length;
      consSynced++;
    }
  }

  // 3) mark papers that have zhihu answer sources (raw article fallback)
  for (const [id, meta] of Object.entries(index)) {
    const p = metaById.get(id);
    meta.ref = p && (p.answerSources || []).filter(s => (s.kind || '').startsWith('知乎')).length || 0;
  }

  const banner = '/** Auto-generated by tools/sync-site-papers.js — do not edit. Updated ' + new Date().toISOString() + ' */\n';
  fs.writeFileSync(path.join(VENDOR, 'papers-index.js'),
    banner + 'window.PapersFullIndex = ' + JSON.stringify(index) + ';\n');

  // 4) 单文件 gzip 包（浏览器用 DecompressionStream 解压）——避免数百个文件和大上传体积
  const zlib = require('zlib');
  const bundle = {};
  for (const f of fs.readdirSync(PAPERS_OUT).filter(f => f.endsWith('.json'))) {
    bundle[f.replace(/\.json$/, '')] = JSON.parse(fs.readFileSync(path.join(PAPERS_OUT, f), 'utf8'));
  }
  const gz = zlib.gzipSync(Buffer.from(JSON.stringify(bundle), 'utf8'), { level: 9 });
  fs.writeFileSync(path.join(VENDOR, 'papers-bundle.json.gz'), gz);

  const totalQs = Object.values(index).reduce((s, v) => s + v.qs.length, 0);
  console.log(JSON.stringify({ papersSynced, pointsSynced, indexPapers: Object.keys(index).length, totalQuestions: totalQs, withPoints: withPoints.size, bundleBytes: gz.length }));
}

function guessType(stem) {
  if (/写一篇文章|自拟题目|主题|话题/.test(stem) && /文章|作文/.test(stem)) return '文章写作';
  if (/讲话稿|公开信|倡议书|提纲|简报|通知|报道|评论|宣传|方案|汇报|发言/.test(stem)) return '公文写作';
  if (/提出.*对策|建议|解决.*问题|措施/.test(stem) && /提出|给出|针对/.test(stem)) return '提出对策';
  if (/谈谈|分析|评价|看法|理解|启示|含义/.test(stem)) return '综合分析';
  return '归纳概括';
}

function materialRange(stem) {
  const m = stem.match(/给定资料\s*([0-9一二三四五六七八九十]+)/);
  return m ? '给定资料' + m[1] : '';
}

main();
