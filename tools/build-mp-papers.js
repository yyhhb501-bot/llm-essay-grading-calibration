'use strict';
// Offline audit and reproducible mini-program index / D1 import generation.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ROOT = path.resolve(__dirname, '..');
const read = name => JSON.parse(fs.readFileSync(path.join(ROOT, name), 'utf8'));
const catalog = read('data/paper-catalog.json').papers;
const index = [], excluded = [], missingScores = [], mismatches = [], records = [];
const seen = new Set();
let materialCount = 0, questionCount = 0;
for (const meta of catalog) {
  if (!/^source_[a-zA-Z0-9_]+$/.test(meta.id) || seen.has(meta.id)) throw new Error('Invalid or duplicate catalog ID: ' + meta.id);
  seen.add(meta.id);
  const file = path.join(ROOT, 'data/papers-full', meta.id + '.json');
  if (!fs.existsSync(file)) { excluded.push({ id: meta.id, title: meta.title, reason: 'missing-file' }); continue; }
  const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
  const materials = doc.materials, questions = doc.questions;
  if (!Array.isArray(materials) || !materials.length || !Array.isArray(questions) || !questions.length) {
    excluded.push({ id: meta.id, title: meta.title, reason: 'empty-materials-or-questions' }); continue;
  }
  if (doc.id !== meta.id || materials.some(m => typeof m.text !== 'string' || !m.text.trim()) ||
      questions.some(q => typeof q.stem !== 'string' || !q.stem.trim())) throw new Error('Malformed content: ' + meta.id);
  const body = JSON.stringify(doc);
  const sha256 = crypto.createHash('sha256').update(body).digest('hex');
  records.push({ id: meta.id, sha256, body });
  questions.forEach((q, i) => {
    if (!(typeof q.score === 'number' && Number.isFinite(q.score) && q.score > 0)) missingScores.push({ paperId: meta.id, questionIndex: i, questionNo: q.no || String(i + 1) });
  });
  const copy = path.join(ROOT, 'site/js/vendor/papers', meta.id + '.json');
  if (!fs.existsSync(copy) || JSON.stringify(JSON.parse(fs.readFileSync(copy, 'utf8'))) !== body) mismatches.push(meta.id);
  materialCount += materials.length;
  questionCount += questions.length;
  index.push({ id: meta.id, title: doc.title || meta.title, year: doc.year || meta.year, region: doc.region || meta.region,
    materials: materials.length, questions: questions.length, recalled: !!meta.recalled || /回忆/.test(doc.title || meta.title) });
}
index.sort((a, b) => b.year - a.year || a.region.localeCompare(b.region, 'zh-CN') || a.title.localeCompare(b.title, 'zh-CN'));
const totals = { papers: index.length, materials: materialCount, questions: questionCount, missingScores: missingScores.length };
const audit = { scope: 'Offline structural audit; original-source textual completeness not certified', catalog: catalog.length,
  ...totals, missingScoreCount: missingScores.length, excluded, missingScores, siteCopyMismatches: mismatches,
  recalled: index.filter(p => p.recalled).length, sourceBytes: records.reduce((n, r) => n + Buffer.byteLength(r.body), 0) };
fs.mkdirSync(path.join(ROOT, '.agent'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'data/mp-papers-index.js'), '// Generated by tools/build-mp-papers.js; metadata only.\nmodule.exports = ' + JSON.stringify({ version: 1, totals, papers: index }) + ';\n');
fs.writeFileSync(path.join(ROOT, 'docs/小程序试卷数据审计.json'), JSON.stringify(audit, null, 2) + '\n');
const quote = value => "'" + value.replace(/'/g, "''") + "'";
fs.writeFileSync(path.join(ROOT, '.agent/mp-papers-import.sql'), records.map(r =>
  'INSERT INTO practice_papers(id,sha256,body) VALUES(' + [r.id, r.sha256, r.body].map(quote).join(',') +
  ') ON CONFLICT(id) DO UPDATE SET sha256=excluded.sha256,body=excluded.body WHERE practice_papers.sha256<>excluded.sha256;'
).join('\n') + '\n');
console.log(JSON.stringify({ ...totals, excluded: excluded.length, siteCopyMismatches: mismatches.length }));
